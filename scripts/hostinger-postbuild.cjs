/**
 * Prepare Next standalone output for Hostinger hbuilds.
 *
 * Hostinger runs: hbuilds/current/nodejs/server.js
 * With Output directory = `.next`, that folder's contents are synced to nodejs/,
 * so we place a launcher at `.next/server.js` and finish standalone assets.
 */
const fs = require("fs");
const path = require("path");

const root = process.cwd();
const nextDir = path.join(root, ".next");
const standaloneDir = path.join(nextDir, "standalone");
const standaloneServer = path.join(standaloneDir, "server.js");

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  fs.cpSync(src, dest, { recursive: true });
}

if (!fs.existsSync(standaloneServer)) {
  console.error(
    "[hostinger-postbuild] Missing .next/standalone/server.js — standalone build failed."
  );
  process.exit(1);
}

const staticSrc = path.join(nextDir, "static");
const staticDest = path.join(standaloneDir, ".next", "static");
if (fs.existsSync(staticSrc)) {
  copyDir(staticSrc, staticDest);
  console.log("[hostinger-postbuild] copied .next/static → standalone");
} else {
  console.warn("[hostinger-postbuild] WARNING: .next/static missing");
}

const publicSrc = path.join(root, "public");
const publicDest = path.join(standaloneDir, "public");
if (fs.existsSync(publicSrc)) {
  copyDir(publicSrc, publicDest);
  console.log("[hostinger-postbuild] copied public → standalone");
}

const envHelperSrc = path.join(root, "scripts", "load-hostinger-env.cjs");
const envHelperDest = path.join(standaloneDir, "load-hostinger-env.cjs");
if (fs.existsSync(envHelperSrc)) {
  fs.copyFileSync(envHelperSrc, envHelperDest);
}

const launcher = `/**
 * Hostinger entry when Output directory is \`.next\` (synced to nodejs/).
 * Generated by scripts/hostinger-postbuild.cjs — do not edit by hand.
 */
process.env.HOSTNAME = process.env.HOSTNAME || "0.0.0.0";
process.env.PORT = process.env.PORT || "3000";

const path = require("path");
const fs = require("fs");

try {
  require("./standalone/load-hostinger-env.cjs");
} catch (err) {
  console.warn("[server] env helper skipped:", err && err.message ? err.message : err);
}

const standaloneDir = path.join(__dirname, "standalone");
const standaloneServer = path.join(standaloneDir, "server.js");

console.log("[server] __dirname=" + __dirname);
console.log("[server] standalone=" + standaloneServer);
console.log("[server] PORT=" + process.env.PORT);

if (!fs.existsSync(standaloneServer)) {
  console.error("[server] FATAL: standalone/server.js missing under", __dirname);
  process.exit(1);
}

process.chdir(standaloneDir);
require(standaloneServer);
`;

fs.writeFileSync(path.join(nextDir, "server.js"), launcher, "utf8");
console.log("[hostinger-postbuild] wrote .next/server.js (Hostinger entry launcher)");
console.log("[hostinger-postbuild] OK — hPanel Output=.next | Entry=server.js");
